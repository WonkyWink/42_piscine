#include <unistd.h>

void	next_num(char *n)
{
	if (n [0] == '7' && n [1] == '8' && n [2] == '9')
	{
		n[3] = '\n';
		write(1, n, 4);
	}
	else
	{
		write(1, n, 5);
	}
}

void	ft_print_comb(void)
{
	char	n[5];

	n[0] = '0';
	n[3] = ',';
	n[4] = ' ';
	while (n[0] <= '7')
	{
		n[1] = n[0] + 1;
		while (n [1] <= '8')
		{
			n [2] = n [1] + 1;
			while (n [2] <= '9')
			{
				next_num(n);
				++ n [2];
			}
			++ n [1];
		}
		++ n [0];
	}
}
